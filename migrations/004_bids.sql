create table bids (
  organization_id text not null references organizations (id),
  opportunity_id text not null references opportunities (id),
  stage text not null,
  labor_low bigint,
  labor_expected bigint,
  labor_high bigint,
  materials_low bigint,
  materials_expected bigint,
  materials_high bigint,
  equipment_low bigint,
  equipment_expected bigint,
  equipment_high bigint,
  subcontractors_low bigint,
  subcontractors_expected bigint,
  subcontractors_high bigint,
  overhead_low bigint,
  overhead_expected bigint,
  overhead_high bigint,
  contingency_low bigint,
  contingency_expected bigint,
  contingency_high bigint,
  profit_low bigint,
  profit_expected bigint,
  profit_high bigint,
  proposed_price bigint,
  approved_by text references users (id),
  approved_by_name text,
  approved_at timestamptz,
  updated_by text references users (id),
  updated_at timestamptz not null default now(),
  primary key (organization_id, opportunity_id),
  constraint bids_stage_chk check (
    stage in (
      'identified',
      'review',
      'qualification',
      'bid_no_bid',
      'pursuit_approved',
      'estimating',
      'proposal_drafting',
      'submitted',
      'closed'
    )
  )
);
